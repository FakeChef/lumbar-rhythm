const stageEncouragementFallback = '设置手术日期后，我可以为你显示更合适的阶段提示。';

String stageForPostSurgeryDay(int postSurgeryDay) {
  if (postSurgeryDay <= 28) {
    return 'P1';
  }
  if (postSurgeryDay <= 56) {
    return 'P2';
  }
  if (postSurgeryDay <= 84) {
    return 'P3';
  }
  return 'P4';
}

String stageEncouragementFor({
  required int postSurgeryDay,
  required DateTime now,
}) {
  final stage = stageForPostSurgeryDay(postSurgeryDay);
  final messages = stageEncouragementMessages[stage] ?? const <String>[];
  if (messages.isEmpty) {
    return stageEncouragementFallback;
  }
  final today = DateTime(now.year, now.month, now.day);
  final index = today.difference(DateTime(1970)).inDays % messages.length;
  return messages[index];
}
